"""Markdown report: policy comparison, per-application deadline misses, Table 9.1 check."""
from __future__ import annotations

from dataclasses import replace
from pathlib import Path

from . import catalog
from .metrics import Summary, by_workload, safety_critical, summarize
from .models import CLOUD, EDGE, FOG, TIERS, Scenario
from .sim import FixedTier, Result, all_policies, simulate

# Table 9.1 as printed in the chapter.
CHAPTER_TABLE = {
    "latency": {CLOUD: "high", EDGE: "low", FOG: "medium"},
    "security": {CLOUD: "moderate", EDGE: "high", FOG: "very high"},
    "cost": {CLOUD: "high", EDGE: "low", FOG: "medium"},
}


def _ms(v: float) -> str:
    return f"{v:,.1f}" if v < 10_000 else f"{v / 1000:,.0f} s"


def run_all(scenario: Scenario) -> dict[str, list[Result]]:
    return {p.name: simulate(scenario, p) for p in all_policies()}


def policy_table(runs: dict[str, list[Result]]) -> str:
    lines = ["| Policy | Tasks | Miss rate (all) | Miss rate (safety-critical) | Safety-critical p99 ms "
             "| Cost USD | Off-premises MB |",
             "|---|---:|---:|---:|---:|---:|---:|"]
    for name, res in runs.items():
        a, s = summarize(res), safety_critical(res)
        lines.append(f"| {name} | {a.n:,} | {a.miss_rate:.2%} | {s.miss_rate:.2%} | {_ms(s.p99_ms)} "
                     f"| {a.cost_usd:,.2f} | {a.off_premises_mb:,.1f} |")
    return "\n".join(lines)


def workload_table(runs: dict[str, list[Result]]) -> str:
    names = list(runs)
    per = {n: by_workload(r) for n, r in runs.items()}
    head = "| Application (section) | Deadline ms | Chapter tier | " + " | ".join(names) + " | adaptive placed on |"
    lines = [head, "|---|---:|---|" + "---:|" * len(names) + "---|"]
    for wl in catalog.WORKLOADS:
        cells = []
        for n in names:
            s: Summary = per[n][wl.key]
            cells.append(f"{s.miss_rate:.0%}" if s.miss_rate else "0")
        mark = " **(safety)**" if wl.safety_critical else ""
        lines.append(f"| {wl.title} ({wl.section}){mark} | {wl.deadline_ms:,.0f} | {wl.chapter_tier} | "
                     + " | ".join(cells) + f" | {per['adaptive'][wl.key].tier_mix} |")
    return "\n".join(lines)


def probe_tiers(duration_s: float = 60.0, seed: int = 7) -> dict[str, dict[str, float]]:
    """Run the reference task alone on each tier, with and without a 15 s cloud/fog outage."""
    out = {}
    for tier in TIERS:
        sc = Scenario("probe", duration_s, seed, dict(catalog.DEFAULT_TIERS), (catalog.REFERENCE_TASK,))
        s = summarize(simulate(sc, FixedTier(tier)))
        down = replace(sc, outages={FOG: ((20.0, 35.0),), CLOUD: ((20.0, 35.0),)})
        d = summarize(simulate(down, FixedTier(tier)))
        out[tier] = {"p50": s.p50_ms, "p99": s.p99_ms, "usd_per_1k": s.cost_usd / s.n * 1000,
                     "off_kb_per_task": s.off_premises_mb * 1000 / s.n, "outage_miss": d.miss_rate}
    return out


def table91(probe: dict[str, dict[str, float]]) -> str:
    lines = ["| Characteristic | " + " | ".join(f"{t} (chapter → simulated)" for t in (CLOUD, EDGE, FOG)) + " |",
             "|---|---|---|---|"]
    row = lambda label, fmt: "| " + label + " | " + " | ".join(fmt(t) for t in (CLOUD, EDGE, FOG)) + " |"
    lines.append(row("Latency", lambda t: f"{CHAPTER_TABLE['latency'][t]} → p50 {probe[t]['p50']:.1f} ms, "
                                          f"p99 {probe[t]['p99']:.1f} ms"))
    lines.append(row("Processing location", lambda t: {CLOUD: "centralised", EDGE: "local device",
                                                         FOG: "distributed (hospital)"}[t]))
    lines.append(row("Cost", lambda t: f"{CHAPTER_TABLE['cost'][t]} → ${probe[t]['usd_per_1k']:.6f} / 1k tasks"))
    lines.append(row("Security (proxy: raw data leaving the hospital)",
                     lambda t: f"{CHAPTER_TABLE['security'][t]} → {probe[t]['off_kb_per_task']:.1f} KB/task off-premises"))
    lines.append(row("Availability (15 s link outage)",
                     lambda t: f"not in table → {probe[t]['outage_miss']:.1%} deadline misses"))
    return "\n".join(lines)


def build_report(duration_s: float = 60.0, seed: int = 7, chart: Path | None = None) -> str:
    base = run_all(catalog.baseline(duration_s, seed))
    outage = run_all(catalog.cloud_outage(duration_s, seed))
    probe = probe_tiers(duration_s, seed)
    if chart is not None:
        _chart({"baseline": base, "cloud outage 20-35 s": outage}, chart)
    parts = [
        "# Simulation results",
        "",
        "> SIMULATION ONLY. All inputs are assumptions (docs/assumptions.md); results show what follows "
        "from those assumptions, not measurements of real hospital systems.",
        "",
        f"Generated by `edgefog report --duration {duration_s:g} --seed {seed}`.",
        "",
        "## 1. Table 9.1 re-examined (reference task, 8 KB in / 0.02 GFLOP)",
        "",
        table91(probe),
        "",
        "## 2. Placement policies, baseline",
        "",
        policy_table(base),
        "",
        "### Deadline-miss rate per application, baseline",
        "",
        workload_table(base),
        "",
        "## 3. Placement policies, cloud link down from 20 s to 35 s",
        "",
        policy_table(outage),
        "",
        "### Deadline-miss rate per application, cloud outage",
        "",
        workload_table(outage),
    ]
    if chart is not None:
        parts += ["", f"![safety-critical deadline misses]({chart.name})"]
    return "\n".join(parts) + "\n"


def _chart(scenarios: dict[str, dict[str, list[Result]]], path: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    policies = list(next(iter(scenarios.values())))
    fig, ax = plt.subplots(figsize=(8, 4))
    width = 0.8 / len(scenarios)
    for i, (label, runs) in enumerate(scenarios.items()):
        vals = [safety_critical(runs[p]).miss_rate * 100 for p in policies]
        xs = [j + i * width for j in range(len(policies))]
        ax.bar(xs, vals, width, label=label)
    ax.set_xticks([j + width * (len(scenarios) - 1) / 2 for j in range(len(policies))], policies)
    ax.set_ylabel("Safety-critical deadline misses (%)")
    ax.set_title("Edge / fog / cloud placement, simulated smart hospital")
    ax.legend()
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)
